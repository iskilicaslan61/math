-- Run this once in the Supabase SQL Editor before starting the application.
CREATE TABLE IF NOT EXISTS settings (
  k TEXT PRIMARY KEY,
  v TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS students (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  grade INTEGER NOT NULL CHECK (grade IN (6, 7)),
  code TEXT NOT NULL UNIQUE,
  created BIGINT NOT NULL,
  last_seen BIGINT
);

CREATE TABLE IF NOT EXISTS assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  ref TEXT NOT NULL,
  title TEXT NOT NULL,
  due TEXT,
  created BIGINT NOT NULL,
  submitted_at BIGINT
);

CREATE TABLE IF NOT EXISTS results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  ref TEXT NOT NULL,
  score INTEGER NOT NULL,
  total INTEGER NOT NULL,
  dur INTEGER NOT NULL DEFAULT 0,
  w TEXT NOT NULL DEFAULT '',
  c TEXT NOT NULL DEFAULT '',
  created BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS mistakes (
  student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  key TEXT NOT NULL,
  n INTEGER NOT NULL DEFAULT 1,
  solved INTEGER NOT NULL DEFAULT 0,
  updated BIGINT NOT NULL,
  PRIMARY KEY (student_id, key)
);

CREATE INDEX IF NOT EXISTS ix_res ON results(student_id, created);
CREATE INDEX IF NOT EXISTS ix_assignments_student ON assignments(student_id, created);

ALTER TABLE settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE students ENABLE ROW LEVEL SECURITY;
ALTER TABLE assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE results ENABLE ROW LEVEL SECURITY;
ALTER TABLE mistakes ENABLE ROW LEVEL SECURITY;
